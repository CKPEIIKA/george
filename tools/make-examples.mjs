// Bundles bergman's own regression inputs and reference outputs
// (vendor/bergman-1.001/tests/test_bergman) into web/src/examples.js.
// The application executes these inputs; stored outputs are validation references.
//
//   node tools/make-examples.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const tests = path.resolve(here, '../vendor/bergman-1.001/tests/test_bergman');
const read = (f) => fs.readFileSync(path.join(tests, f), 'latin1');

// task ids are the ones used by app.js (TASKS)
const EXAMPLES = [
  { id: 'simple_c', title: 'Commutative: 5xy, x² − y²', task: 'gb', input: 'simple_c', out: { gb: 'simple_c.gb.old' } },
  { id: 'simple_nc', title: 'Noncommutative: xy', task: 'gb', input: 'simple_nc', out: { gb: 'simple_nc.gb.old' } },
  { id: 'char5', title: 'Characteristic 5', task: 'gb', input: 'char5', out: { gb: 'char5.gb.old' } },
  { id: 'char2', title: 'Characteristic 2', task: 'gb', input: 'char2', out: { gb: 'char2.gb.old' } },
  { id: 'simp_weight_nc', title: 'Weighted variables (1, 1, 2)', task: 'gb', input: 'simp_weight_nc', out: { gb: 'simp_weight_nc.gb.old' } },
  { id: 'matrix', title: 'Matrix ordering (commutative)', task: 'gb', input: 'matrix', out: { gb: 'matrix.gb.old' },
    session: { weights: '1 2 1', matrix: '1 2 1\n0 -1 1\n3 -2 2' } },
  { id: 'hilb', title: 'Hilbert series (commutative)', task: 'hilbert', input: 'hilb', out: { gb: 'hilb.gb.old', hs: 'hilb.hs.old' } },
  { id: 'ncpbhg', title: 'Hilbert and Poincaré–Betti series', task: 'ncpbh', input: 'ncpbhg',
    out: { gb: 'ncpbhg.gb.old', hs: 'ncpbhg.hs.old', pb: 'ncpbhg.pb.old' } },
  { id: 'anick_tm', title: 'Anick resolution of the trivial module', task: 'anick', input: 'anick_tm',
    out: { gb: 'anick_tm.res.old', anick: 'anick_tm.out.old' } },
  { id: 'modbtn', title: 'Betti numbers of a right module', task: 'rmodule', input: 'modbtn',
    out: { gb: 'modbtn.res.old', anick: 'modbtn.out.old' } },
  { id: 'leftmodbtn', title: 'Betti numbers of a left module', task: 'lmodule', input: 'leftmodbtn',
    out: { gb: 'leftmodbtn.res.old', anick: 'leftmodbtn.out.old' } },
  { id: 'two', title: 'Betti numbers for two modules', task: 'twomod', input: 'two', out: { gb: 'two.res.old', anick: 'two.out.old' } },
  { id: 'fact', title: 'Betti numbers of a factor-algebra', task: 'factalg', input: 'fact', out: { gb: 'fact.res.old', anick: 'fact.out.old' } },
  { id: 'hoch1', title: 'Hochschild homology', task: 'hochschild', input: 'hochschild1', out: { gb: 'hoch1.res.old', anick: 'hoch1.out.old' } },
];

const data = EXAMPLES.map((e) => {
  const out = {};
  for (const [k, f] of Object.entries(e.out)) out[k] = read(f);
  return { ...e, input: read(e.input), inputName: e.input, out };
});

const banner = '// Generated by tools/make-examples.mjs from vendor/bergman-1.001/tests/test_bergman. Do not edit.\n' +
  '// Inputs and outputs are bergman\'s own regression files (Bergman General Public License).\n';
fs.writeFileSync(path.join(here, '../web/src/examples.js'), banner + 'export const EXAMPLES = ' + JSON.stringify(data, null, 1) + ';\n');
console.log('wrote examples.js with', data.length, 'examples');
