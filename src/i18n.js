let language = 'en';
export const LANGUAGES = ['en', 'ru'];
export function getLanguage() { return language; }
export function setLanguage(value) { language = LANGUAGES.includes(value) ? value : 'en'; }
export function t(key, params = {}) {
  const value = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (match, name) => String(params[name] ?? match));
}
// n === 1 uses "<key>.one" when the current language defines it.
export function tn(key, n, params = {}) {
  const one = key + '.one';
  return t(n === 1 && STRINGS[language][one] !== undefined ? one : key, { ...params, n });
}
export function applyTranslations(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}
const escapePattern = s => s.replace(/[.*+?^{}$()|[\]\\]/g, '\\$&');
const messages = Object.entries(STRINGS.en).filter(([key]) => /^(err|syn)\./.test(key)).map(([key, value]) => {
  const names = [...value.matchAll(/\{(\w+)\}/g)].map(m => m[1]);
  const pattern = value.split(/\{\w+\}/).map(escapePattern).join('(.+?)');
  return { key, names, pattern: new RegExp('^' + pattern + '$') };
});
export function translateMessage(message) {
  if (language === 'en') return message;
  for (const entry of messages) {
    const match = entry.pattern.exec(message);
    if (match) return t(entry.key, Object.fromEntries(entry.names.map((name, i) => [name, match[i + 1]])));
  }
  return message; // Bergman's raw Lisp diagnostics keep their original text.
}
